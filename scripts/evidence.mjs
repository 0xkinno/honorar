import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { delimiter, join } from 'node:path';

const PATH = `${join(homedir(), '.foundry', 'bin')}${delimiter}${process.env.PATH}`;
const run = (cmd, cwd) => execSync(cmd, { cwd, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024, env: { ...process.env, PATH } });

function forgeCount() {
  const out = JSON.parse(run('forge test --json', 'contracts'));
  let n = 0;
  for (const suite of Object.values(out)) {
    for (const t of Object.values(suite.test_results)) if (t.status === 'Success') n++;
  }
  return n;
}

function vitestCount(dir) {
  const out = run('npx vitest run --reporter=json', dir);
  const j = JSON.parse(out.slice(out.indexOf('{')));
  return j.numPassedTests;
}

const counts = {
  forge: forgeCount(),
  kernel: vitestCount('packages/kernel'),
  verifier: vitestCount('packages/verifier'),
  agent: vitestCount('services/agent'),
};
mkdirSync('evidence', { recursive: true });
writeFileSync('evidence/tests.json', `${JSON.stringify({ ...counts, ranAt: new Date().toISOString() }, null, 2)}\n`);

const dep = existsSync('deployments/arc-mainnet.json') ? JSON.parse(readFileSync('deployments/arc-mainnet.json', 'utf8')) : null;
const seed = existsSync('evidence/mainnet/seed.json') ? JSON.parse(readFileSync('evidence/mainnet/seed.json', 'utf8')) : null;
const x = 'https://explorer.arc.io';
const lines = ['# EVIDENCE', '', 'Generated by `scripts/evidence.mjs`. Do not edit by hand.', ''];
lines.push('## Tests', '', `- Foundry: ${counts.forge} passing`, `- Kernel: ${counts.kernel} passing`, `- Verifier: ${counts.verifier} passing`, `- Agent: ${counts.agent} passing`, '');
lines.push('## Arc mainnet (chain id 5042)', '');
if (dep) {
  lines.push(`- HonorarRegistry: [${dep.registry}](${x}/address/${dep.registry}), tx [${dep.registryTx}](${x}/tx/${dep.registryTx})`);
  lines.push(`- HonorarLedger: [${dep.ledger}](${x}/address/${dep.ledger}), tx [${dep.ledgerTx}](${x}/tx/${dep.ledgerTx})`);
  lines.push(`- Deployed ${dep.deployedAt} at block ${dep.block}, solc ${dep.compiler.solc}, optimizer runs ${dep.compiler.optimizerRuns}`);
} else {
  lines.push('- Not deployed yet.');
}
lines.push('');
if (seed) {
  lines.push('## Registered work', '', `- workId \`${seed.workId}\``, `- registerWork: [${seed.registerTx}](${x}/tx/${seed.registerTx})`, '');
}
import { readdirSync } from 'node:fs';
const mainnetDir = 'evidence/mainnet';
if (existsSync(mainnetDir)) {
  const answers = readdirSync(mainnetDir).filter((n) => /^0x[0-9a-f]{10}\.json$/.test(n) || n === 'answer-1.json');
  const rows = [];
  for (const n of answers) {
    const b = JSON.parse(readFileSync(`${mainnetDir}/${n}`, 'utf8'));
    if (!b.strike) continue;
    rows.push(`| \`${b.answerId.slice(0, 12)}\` | ${b.leaves.length} | [${b.strike.txHash.slice(0, 12)}...](${x}/tx/${b.strike.txHash}) | ${b.strike.blockNumber} | ${b.transferIds.length} |`);
  }
  if (rows.length) lines.push('## Struck answers on mainnet', '', '| Answer | Leaves | Strike tx | Block | Reading fees |', '|---|---|---|---|---|', ...rows, '', 'Each bundle is in `evidence/mainnet/` and verifies with the CLI.', '');
  if (existsSync(`${mainnetDir}/erc8004.json`)) {
    const r = JSON.parse(readFileSync(`${mainnetDir}/erc8004.json`, 'utf8'));
    lines.push('## ERC-8004 agent identity', '', `- Agent id ${r.agentId}, registration tx [${r.txHash}](${x}/tx/${r.txHash}), metadata ${r.metadataUri}`, '');
  }
  if (existsSync(`${mainnetDir}/feedback.json`)) {
    const f = JSON.parse(readFileSync(`${mainnetDir}/feedback.json`, 'utf8'));
    lines.push(`- Validator feedback entries: ${f.feedback.length}`, ...f.feedback.map((e) => `  - ${e.answerId.slice(0, 12)} score ${e.score}: [${e.tx.slice(0, 12)}...](${x}/tx/${e.tx})`), '');
  }
}
writeFileSync('EVIDENCE.md', `${lines.join('\n')}\n`);
process.stdout.write(`evidence written: ${JSON.stringify(counts)}\n`);
